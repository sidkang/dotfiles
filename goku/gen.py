#!/usr/bin/env python3
"""Generate the key-menu regions of karabiner.edn and the WhichKey groups from menus.toml.

    python3 goku/gen.py          write generated files
    python3 goku/gen.py --check  exit 1 if generated files are out of date
"""

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
EDN = ROOT / "karabiner.edn"
MENUS = ROOT / "menus.toml"
GROUPS = ROOT.parent / "hammerspoon" / "sids" / "whichkey" / "groups.lua"
GROUPS_HEADER = "-- Generated by goku/gen.py from goku/menus.toml. Do not edit.\n"


def quote(value: str) -> str:
    """EDN and Lua share the same escaping for the strings used here."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hide_command(menu: dict) -> str:
    group = "" if menu.get("hide_group") is False else f"&group={menu['id']}"
    return f"[:hs {quote('whichkey?action=hide' + group)}]"


def menu_rules(menu: dict) -> list[str]:
    mid = quote(menu["id"])
    lines = [f":{menu['id']}"]
    if exit_key := menu.get("exit"):
        lines.append(f"[:{exit_key} [[{mid} 0] {hide_command(menu)}]]")
    for item in menu["items"]:
        template, _, argument = item["cmd"].partition(":")
        keys = item.get("keys") or [item["key"]]
        for key, ident in zip(keys, item.get("ids", keys)):
            arg = argument.replace("{key}", key).replace("{KEY}", key.upper()).replace("{ID}", ident)
            lines.append(f"[:{key} [[{mid} 0] [:{template} {quote(arg)}]] nil {{:afterup {hide_command(menu)}}}]")
    return lines


def render_region(menus: list[dict], indent: str) -> str:
    lines: list[str] = []
    for menu in menus:
        lines.extend(menu_rules(menu))
        lines.append("")
    return "\n".join(indent + line if line else "" for line in lines[:-1]) + "\n"


def update_edn(text: str, menus: list[dict]) -> str:
    regions: dict[str, list[dict]] = {}
    for menu in menus:
        if menu.get("generate", True):
            regions.setdefault(menu["region"], []).append(menu)

    for name, items in regions.items():
        pattern = re.compile(
            rf"^([ \t]*);; BEGIN menus:{re.escape(name)}\b[^\n]*\n.*?^[ \t]*;; END menus:{re.escape(name)}\n",
            re.S | re.M,
        )
        match = pattern.search(text)
        if match is None:
            raise SystemExit(f"karabiner.edn: missing region markers for '{name}'")
        indent = match.group(1)
        block = (
            f"{indent};; BEGIN menus:{name} (generated from menus.toml)\n"
            f"{render_region(items, indent)}"
            f"{indent};; END menus:{name}\n"
        )
        text = text[: match.start()] + block + text[match.end() :]
    return text


def render_groups(menus: list[dict]) -> str:
    out = [GROUPS_HEADER, "return {\n"]
    for menu in menus:
        out.append(f"\t[{quote(menu['id'])}] = {{\n\t\ttitle = {quote(menu['title'])},\n")
        if menu.get("exit"):
            out.append("\t\texit = true,\n")
        if menu.get("footer"):
            out.append(f"\t\tfooter = {quote(menu['footer'])},\n")
        out.append("\t\titems = {\n")
        for item in menu["items"]:
            label = item.get("label") or item["key"].upper()
            out.append(f"\t\t\t{{ key = {quote(label)}, desc = {quote(item['desc'])} }},\n")
        out.append("\t\t},\n\t},\n")
    out.append("}\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    menus = tomllib.loads(MENUS.read_text())["menu"]
    edn = update_edn(EDN.read_text(), menus)
    groups = render_groups(menus)

    if "--check" in argv:
        stale = [p.name for p, new in ((EDN, edn), (GROUPS, groups)) if not p.exists() or p.read_text() != new]
        if stale:
            print("out of date: " + ", ".join(stale) + " (run: mise run goku:gen)", file=sys.stderr)
            return 1
        return 0

    EDN.write_text(edn)
    GROUPS.parent.mkdir(parents=True, exist_ok=True)
    GROUPS.write_text(groups)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
